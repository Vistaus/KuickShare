#!/usr/bin/env python3
"""Helper for the gettext catalogs in po/ (stdlib only).

  po.py todo                 pending entries (untranslated or fuzzy) of every language, as JSON
  po.py apply FILE.json      write translations: {"it": {"<msgid>": "<msgstr>", ...}, ...}
  po.py status               translated / fuzzy / untranslated counts per language

`apply` matches the message by its full msgid, clears the fuzzy flag and leaves everything else
alone. The catalogs are regenerated by `build/build-env.sh po/extract.sh`, never edited by hand.
"""

import json
import re
import sys
from pathlib import Path

PO_DIR = Path(__file__).resolve().parents[2] / "po"


def languages() -> list[str]:
    return (PO_DIR / "LINGUAS").read_text().split()


def unquote(lines: list[str]) -> str:
    """Joins the quoted pieces of a msgid/msgstr block and resolves the escapes we use."""
    out = ""
    for line in lines:
        match = re.match(r'^(?:msgid|msgstr|msgctxt)?\s*"(.*)"$', line)
        if match:
            out += match.group(1)
    return out.replace('\\"', '"').replace("\\n", "\n").replace("\\\\", "\\")


def quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def split_entry(block: str) -> tuple[list[str], str, int, int] | None:
    """Returns (lines, msgid, index of msgid line, index of msgstr line) or None for non-messages."""
    lines = block.split("\n")
    start = next((i for i, line in enumerate(lines) if line.startswith("msgid ")), None)
    stop = next((i for i, line in enumerate(lines) if line.startswith("msgstr")), None)
    if start is None or stop is None or any(line.startswith("msgid_plural") for line in lines):
        return None
    return lines, unquote(lines[start:stop]), start, stop


def read_blocks(lang: str) -> list[str]:
    return (PO_DIR / f"{lang}.po").read_text(encoding="utf-8").split("\n\n")


def pending(lang: str) -> list[str]:
    result = []
    for block in read_blocks(lang):
        entry = split_entry(block)
        if entry is None or not entry[1]:  # the header has an empty msgid
            continue
        lines, msgid, _, stop = entry
        if "#, fuzzy" in lines or not unquote(lines[stop:]):
            result.append(msgid)
    return result


def apply(translations: dict[str, dict[str, str]]) -> dict[str, int]:
    applied = {}
    for lang, messages in translations.items():
        blocks = read_blocks(lang)
        done = 0
        for i, block in enumerate(blocks):
            entry = split_entry(block)
            if entry is None or entry[1] not in messages:
                continue
            lines, msgid, start, stop = entry
            kept = [line for line in lines[:start] if line != "#, fuzzy"]
            blocks[i] = "\n".join(kept + lines[start:stop] + ["msgstr " + quote(messages[msgid])])
            done += 1
        (PO_DIR / f"{lang}.po").write_text("\n\n".join(blocks), encoding="utf-8")
        applied[lang] = done
    return applied


def main(argv: list[str]) -> int:
    command = argv[1] if len(argv) > 1 else ""
    if command == "todo":
        todo = {lang: pending(lang) for lang in languages()}
        print(json.dumps({lang: ids for lang, ids in todo.items() if ids}, ensure_ascii=False, indent=2))
    elif command == "apply" and len(argv) == 3:
        translations = json.loads(Path(argv[2]).read_text(encoding="utf-8"))
        print(json.dumps(apply(translations)))
    elif command == "status":
        for lang in languages():
            print(f"{lang}: {len(pending(lang))} pending")
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
