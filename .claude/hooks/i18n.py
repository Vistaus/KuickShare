#!/usr/bin/env python3
"""Hooks for the translations (stdin: the hook event as JSON).

PreToolUse  Edit/Write of po/kuickshare.pot  -> denied (generated by po/extract.sh)
PostToolUse Edit/Write of a file in po/POTFILES.in whose change mentions i18n -> reminder
PostToolUse Bash running po/extract.sh       -> tells how many entries are pending
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def answer(event: str, **fields: object) -> None:
    print(json.dumps({"hookSpecificOutput": {"hookEventName": event, **fields}}))


def relative(path: str) -> str:
    try:
        return str(Path(path).resolve().relative_to(ROOT))
    except ValueError:
        return path


def main() -> None:
    data = json.load(sys.stdin)
    tool_input = data.get("tool_input", {})
    event = data.get("hook_event_name", "")
    path = relative(tool_input.get("file_path", ""))

    if event == "PreToolUse":
        if path == "po/kuickshare.pot":
            answer(
                "PreToolUse",
                permissionDecision="deny",
                permissionDecisionReason="po/kuickshare.pot is generated: run `build/build-env.sh po/extract.sh`.",
            )
        return

    if data.get("tool_name") == "Bash":
        if "po/extract.sh" not in tool_input.get("command", ""):
            return
        pending = subprocess.run(
            [sys.executable, str(ROOT / ".claude/scripts/po.py"), "status"], capture_output=True, text=True
        ).stdout.strip()
        answer(
            "PostToolUse",
            additionalContext=(
                "Catalogs regenerated. Pending entries:\n"
                f"{pending}\n"
                "If any is pending, hand them to the `translator` agent (see /update-translations)."
            ),
        )
        return

    sources = (ROOT / "po/POTFILES.in").read_text().split()
    changed = " ".join(str(tool_input.get(key, "")) for key in ("new_string", "content"))
    if path in sources and "i18n" in changed:
        answer(
            "PostToolUse",
            additionalContext=(
                f"{path} has translatable strings. When the i18n() edits are done, run /update-translations "
                "(extract the catalogs, then the `translator` agent)."
            ),
        )


if __name__ == "__main__":
    main()
